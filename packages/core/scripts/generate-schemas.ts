import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const schemaDir = fileURLToPath(
  new URL('../../../format/v0/schema/', import.meta.url),
);
const outFile = fileURLToPath(
  new URL('../src/generated/schemas.ts', import.meta.url),
);

const names = readdirSync(schemaDir)
  .filter((name) => name.endsWith('.schema.json'))
  .sort();

const entries = names.map((name) => {
  const schema: unknown = JSON.parse(
    readFileSync(`${schemaDir}${name}`, 'utf8'),
  );
  const literal = JSON.stringify(schema, null, 2).replace(/\n/g, '\n  ');
  return `  ${JSON.stringify(name)}: ${literal},`;
});

const text = [
  '// Generated by packages/core/scripts/generate-schemas.ts from format/v0/schema. Do not edit.',
  'export const schemaFiles: Readonly<Record<string, unknown>> = {',
  ...entries,
  '};',
  '',
].join('\n');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, text);
console.log(`Wrote ${names.length} schemas to ${outFile}`);
